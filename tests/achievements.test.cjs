const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
vm.runInThisContext(fs.readFileSync(require('node:path').join(__dirname, '../achievements.js'), 'utf8'));
const A = globalThis.MetroAchievements, now = '2026-11-06T12:00:00.000Z';
let p = A.empty();
assert.equal(A.stats(p).rides, 0);
p = A.start(p, 'TSQ', 'BARC', 'trip1');
p = A.complete(p, now);
assert.equal(p.unlocked['first-trip'], now);
assert.equal(A.stats(p).stations, 2);
assert.equal(A.complete(p, now).trips.length, 1);
p = A.normalize(JSON.parse(JSON.stringify(p)));
assert.equal(A.complete(p, now).trips.length, 1);
for (let i=2;i<=20;i++) p=A.complete(A.start(p,'TSQ','station'+i,'trip'+i),now);
assert.equal(A.stats(p).rides,20);
assert.ok(p.unlocked['five-trips'] && p.unlocked['twenty-trips']);
assert.ok(p.unlocked['five-stations'] && p.unlocked['ten-stations']);
p=A.bookmark(p,now);
assert.equal(Object.keys(p.unlocked).length,6);
assert.equal(A.bookmark(p,'2026-11-07T12:00:00Z').unlocked['first-favorite'],now);
assert.equal(A.complete(A.start(p,'TSQ','TSQ','invalid'),now).trips.length,20);
assert.equal(A.normalize(null).trips.length,0);
assert.equal(A.normalize({version:1,trips:[null,{},p.trips[0],p.trips[0]]}).trips.length,1);
console.log('PASS: thresholds, unique stations, duplicate/reload protection, same-station rejection, bookmark idempotency, invalid stored records');
