const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const assert = require('node:assert/strict');
for (const file of ['carbon.js', 'achievements.js', 'distance.js', 'eco-score.js']) vm.runInThisContext(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'));
const C = MetroCarbon, E = MetroEcoScore, A = MetroAchievements;
const estimate = (car, train) => C.estimate({ drivingDistance: car, transitDistance: train, unit: 'km', baselineMode: 'solo-petrol-car', distanceSource: 'Test route source' });
const short = E.fromSnapshot(estimate(2, 2)), long = E.fromSnapshot(estimate(20, 20));
assert.ok(long.value > short.value);
assert.ok(E.fromSnapshot(estimate(20, 25)).value < long.value); // Same endpoints, longer transit detour lowers score.
assert.equal(E.fromSnapshot(estimate(1, 100)).value, 0);
assert.equal(E.fromSnapshot(null), null);
assert.equal(E.fromSnapshot({ status: 'unavailable' }), null);
assert.ok(E.fromSnapshot(estimate(2000, 2000)).value <= 100);
const original = estimate(10, 10), before = JSON.stringify(original);
const recorded = E.attach(original);
assert.equal(JSON.stringify(original), before);
assert.ok(C.validSnapshot(recorded));
assert.equal(recorded.ecoScore.modelVersion, 'eco-benefit-v1');
let progress = A.complete(A.start(A.empty(), 'TSQ', 'BARC', 'legacy'), '2026-11-20T12:00:00Z', original);
const legacy = JSON.stringify(progress.trips[0]);
progress = A.complete(A.start(progress, 'TSQ', 'PENN', 'scored'), '2026-11-20T12:01:00Z', recorded);
const restored = A.normalize(JSON.parse(JSON.stringify(progress)));
assert.equal(JSON.stringify(restored.trips[0]), legacy);
assert.deepEqual(restored.trips[1].carbon.ecoScore, recorded.ecoScore);
assert.equal(A.complete(restored, '2026-11-20T12:02:00Z', recorded).trips.length, 2);
assert.equal(C.summarize(restored.trips).estimatedJourneys, 2);
assert.equal(restored.unlocked['first-trip'], '2026-11-20T12:00:00Z');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/transit-network.json'), 'utf8'));
const routes = MetroDistance.planRoutes(MetroDistance.prepare(data), '127', '235');
const road = { drivingDistanceKm: 12, roadSource: 'https://example.com', fetchedAt: '2026-11-20T12:00:00Z' };
const ranked = E.rankRoutes(routes, road);
assert.equal(ranked.filter(r => r.ecoRecommended).length, 1);
assert.ok(ranked[0].ecoRecommended);
assert.deepEqual(E.rankRoutes(routes, null).map(r => r.ecoScore), routes.map(() => null));
const detour = { ...routes[0], id: 99, duration: 1, transitDistanceKm: routes[0].transitDistanceKm * 2,
  trainSegments: routes[0].trainSegments.map(s => ({ ...s, distanceKm: s.distanceKm * 2 })) };
assert.notEqual(E.rankRoutes([detour, routes[0]], road)[0].id, 99);
assert.equal(E.rankRoutes(routes, { ...road, drivingDistanceKm: .1 }).some(r => r.ecoRecommended), false);
assert.deepEqual(routes.map(r => r.ecoScore), routes.map(() => undefined));
console.log('PASS: longer comparable trips score higher, detours penalized, missing/negative handling, Eco ranking, immutable snapshots, legacy/achievement preservation');
